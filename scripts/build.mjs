#!/usr/bin/env node
/**
 * 构建两个半侧：
 *   src/host/index.js  -> lib/index.js   （ESM，schemastery 内联，零运行时依赖）
 *   src/client/index.jsx -> lib/client.js（lazy-CJS factory，react 外置，由浏览器模块表提供）
 *
 * 不用 tsdown / 官方 clientBundle 预设，因为它们不随包发布；这里复刻同样的产物形状。
 */

import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
// 客户端 lazy factory 的 id 必须等于包名，浏览器模块加载器按包名登记。
const PACKAGE_NAME = '@wjunhere/dsh-prompt-lab'

/** 把 esbuild 的 CJS 产物包成浏览器模块加载器认识的 lazy factory。 */
function wrapClientBundle(code) {
  const indented = code
    .split('\n')
    .map(line => (line === '' ? '' : `    ${line}`))
    .join('\n')
  return `/* dsh-prompt-lab client bundle — generated by scripts/build.mjs, do not edit. */
window.__ModuleLoader__.load({
  id: '${PACKAGE_NAME}',
  factory(require) {
    const module = { exports: {} };
    (function (module, exports, require) {
${indented}
    })(module, module.exports, require);
    return module.exports;
  },
});
`
}

async function buildHost() {
  await build({
    entryPoints: [join(ROOT, 'src', 'host', 'index.js')],
    outfile: join(ROOT, 'lib', 'index.js'),
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    sourcemap: false,
    legalComments: 'none',
    banner: { js: '/* dsh-prompt-lab host bundle — generated by scripts/build.mjs, do not edit. */' },
  })
}

async function buildClient() {
  const result = await build({
    entryPoints: [join(ROOT, 'src', 'client', 'index.jsx')],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: 'es2020',
    jsx: 'transform',
    external: ['react'],
    legalComments: 'none',
    outfile: join(ROOT, 'lib', 'client.js'),
  })
  const code = result.outputFiles[0].text
  await writeFile(join(ROOT, 'lib', 'client.js'), wrapClientBundle(code), 'utf8')
}

await mkdir(join(ROOT, 'lib'), { recursive: true })
await buildHost()
await buildClient()
process.stdout.write('dsh-prompt-lab: built lib/index.js and lib/client.js\n')
